export function bookingClaimReason(language, reason) {
  if (resolveBookingLanguage(language) !== "hi" || typeof reason !== "string") return reason;
  const known = {
    "line incomplete": "लाइन पूरी नहीं हुई",
    "full house incomplete": "फुल हाउस पूरा नहीं हुआ",
    "corners incomplete": "चारों कोने पूरे नहीं हुए",
    "star incomplete": "स्टार पैटर्न पूरा नहीं हुआ",
    "box incomplete": "बॉक्स पैटर्न पूरा नहीं हुआ",
    "half sheet is judged across three of your tickets, not on one": "आधी शीट तीन टिकटों पर जाँची जाती है, एक टिकट पर नहीं",
  };
  if (known[reason]) return known[reason];
  const few = reason.match(/^fewer than (\d+) ticket numbers called$/);
  if (few) return `टिकट के अभी ${formatBookingNumber(few[1], language)} नंबर ही बोले गए`;
  const needTickets = reason.match(/^half sheet needs three tickets, this seat holds (\d+)$/);
  if (needTickets) return `आधी शीट के लिए तीन टिकट चाहिए; इस सीट पर ${formatBookingNumber(needTickets[1], language)} हैं`;
  const scoredTickets = reason.match(/^only (\d+) of your tickets have two numbers called$/);
  if (scoredTickets) return `आपके केवल ${formatBookingNumber(scoredTickets[1], language)} टिकटों पर दो नंबर बोले गए`;
  const earlyWindow = reason.match(/^early five window of (\d+) calls already passed$/);
  if (earlyWindow) return `अर्ली फाइव की ${formatBookingNumber(earlyWindow[1], language)} कॉल की सीमा निकल गई`;
  return reason;
}

function formattingLocale(language) {
  language = resolveBookingLanguage(language);
  if (typeof navigator === "undefined") return language === "hi" ? "hi-IN" : "en-US";
  const raw = String(navigator.language || "en-US");
  const region = raw.split("-").slice(1).find((part) => /^[A-Za-z]{2}$|^\d{3}$/.test(part));
  const normalizedRegion = region ? region.toUpperCase() : (language === "hi" ? "IN" : "US");
  return `${language === "hi" ? "hi" : "en"}-${normalizedRegion}`;
}

export function formatBookingDate(value, language) {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return bookingCopy(language, "timeUnknown");
  return new Intl.DateTimeFormat(formattingLocale(language), {
    year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit", timeZoneName: "short",
  }).format(date);
}

export function formatBookingNumber(value, language) {
  language = resolveBookingLanguage(language);
  const locale = formattingLocale(language);
  return new Intl.NumberFormat(language === "hi" ? `${locale}-u-nu-deva` : locale).format(Number(value));
}

export function localizeBookingDigits(language, value) {
  const text = String(value ?? "");
  if (resolveBookingLanguage(language) !== "hi") return text;
  const digits = "०१२३४५६७८९";
  return text.replace(/[0-9]/g, (digit) => digits[Number(digit)]);
}
